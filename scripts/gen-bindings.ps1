# Regenerate crates/dfin-llama-sys/src/bindings.rs from the vendored llama.h.
# Requires: bindgen-cli (cargo install bindgen-cli) and LLVM (libclang.dll).
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
if (-not $env:LIBCLANG_PATH) {
    if (Test-Path "C:\Program Files\LLVM\bin\libclang.dll") { $env:LIBCLANG_PATH = "C:\Program Files\LLVM\bin" }
}
$inc = Join-Path $root "vendor\llama.cpp\include"
$ggmlInc = Join-Path $root "vendor\llama.cpp\ggml\include"
$out = Join-Path $root "crates\dfin-llama-sys\src\bindings.rs"
bindgen (Join-Path $inc "llama.h") -o $out `
    --allowlist-function "llama_.*" `
    --allowlist-function "ggml_backend_.*" `
    --allowlist-function "ggml_log_.*" `
    --allowlist-type "llama_.*" `
    --allowlist-type "ggml_.*" `
    --allowlist-var "LLAMA_.*" `
    --allowlist-var "GGML_.*" `
    --no-prepend-enum-name `
    --no-doc-comments `
    --raw-line "// Generated by scripts/gen-bindings.ps1 from vendor/llama.cpp/include/llama.h. Do not edit." `
    -- -I $inc -I $ggmlInc --target=x86_64-pc-windows-msvc
Write-Host "wrote $out"
