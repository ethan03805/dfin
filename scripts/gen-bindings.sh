#!/usr/bin/env bash
# Regenerate crates/dfin-llama-sys/src/bindings.rs from the vendored llama.h (Linux/macOS).
# Requires bindgen-cli (cargo install bindgen-cli) and libclang (Xcode CLT on macOS,
# libclang-dev on Debian/Ubuntu). The checked-in bindings were generated on Windows x64;
# llama.h uses fixed-width integers so they normally work everywhere, but regenerate if the
# layout tests in `cargo test -p dfin-llama-sys` fail on your platform.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
inc="$root/vendor/llama.cpp/include"
ggml_inc="$root/vendor/llama.cpp/ggml/include"
out="$root/crates/dfin-llama-sys/src/bindings.rs"
bindgen "$inc/llama.h" -o "$out" \
    --allowlist-function 'llama_.*' \
    --allowlist-function 'ggml_backend_.*' \
    --allowlist-function 'ggml_log_.*' \
    --allowlist-type 'llama_.*' \
    --allowlist-type 'ggml_.*' \
    --allowlist-var 'LLAMA_.*' \
    --allowlist-var 'GGML_.*' \
    --no-prepend-enum-name \
    --no-doc-comments \
    --raw-line '// Generated by scripts/gen-bindings.sh from vendor/llama.cpp/include/llama.h. Do not edit.' \
    -- -I "$inc" -I "$ggml_inc"
echo "wrote $out"
